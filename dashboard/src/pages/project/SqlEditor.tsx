import { useState, type KeyboardEvent } from "react";
import { api, ApiError, type Project, type QueryResponse } from "../../api";
import { Button, Card, Notice } from "../../ui";

const starter: Record<string, string> = {
  postgres: "create table todos (\n  id bigint generated by default as identity primary key,\n  title text not null,\n  done boolean not null default false\n);\n\nselect * from todos;",
  mysql: "create table todos (\n  id bigint auto_increment primary key,\n  title varchar(255) not null,\n  done boolean not null default false\n);\n\nselect * from todos;",
};

// The last query is kept per project in this browser only.
function savedQuery(ref: string, engine: string): string {
  try {
    return localStorage.getItem(`flobase.sql.${ref}`) ?? starter[engine] ?? "";
  } catch {
    return starter[engine] ?? "";
  }
}

function saveQuery(ref: string, query: string) {
  try {
    localStorage.setItem(`flobase.sql.${ref}`, query);
  } catch {
    // Storage can be blocked; the query just won't be remembered.
  }
}

export function SqlEditor({ project }: { project: Project }) {
  const [query, setQuery] = useState(() => savedQuery(project.ref, project.engine));
  const [result, setResult] = useState<QueryResponse | null>(null);
  const [error, setError] = useState<ApiError | null>(null);
  const [running, setRunning] = useState(false);

  const run = async () => {
    setRunning(true);
    setError(null);
    saveQuery(project.ref, query);
    try {
      setResult(await api.sql(project.ref, query));
    } catch (e) {
      setResult(null);
      setError(e instanceof ApiError ? e : new ApiError(0, (e as Error).message));
    } finally {
      setRunning(false);
    }
  };

  const onKey = (e: KeyboardEvent<HTMLTextAreaElement>) => {
    if (e.key === "Enter" && (e.metaKey || e.ctrlKey)) {
      e.preventDefault();
      if (!running) run();
    }
  };

  // Show the last statement that returned columns; earlier statements
  // are summarised by their command tags.
  const shown = result ? [...result.results].reverse().find((r) => r.columns.length > 0) : undefined;
  const isMac = typeof navigator !== "undefined" && /Mac/.test(navigator.platform);

  return (
    <div className="flex flex-col gap-4">
      <Card className="overflow-hidden">
        <label htmlFor="sql" className="sr-only">
          SQL query
        </label>
        <textarea
          id="sql"
          value={query}
          onChange={(e) => setQuery(e.target.value)}
          onKeyDown={onKey}
          spellCheck={false}
          rows={12}
          className="code block w-full resize-y bg-surface-sunken p-4 text-ink outline-none"
        />
        <div className="flex flex-wrap items-center justify-between gap-3 border-t border-border px-4 py-3">
          <span className="body-sm text-ink-muted">
            Runs as the database owner. {isMac ? "⌘" : "Ctrl"} + Enter to run.
          </span>
          <Button variant="primary" onClick={run} disabled={running || !query.trim()}>
            {running ? "Running…" : "Run"}
          </Button>
        </div>
      </Card>

      {error && (
        <Notice tone="danger">
          {error.message}
          {error.detail?.detail ? ` ${error.detail.detail}` : ""}
          {error.detail?.hint ? ` Hint: ${error.detail.hint}` : ""}
          {error.detail?.position ? ` (at character ${error.detail.position})` : ""}
        </Notice>
      )}

      {result && (
        <div className="flex flex-col gap-3">
          <p className="body-sm text-ink-muted">
            <span className="font-mono">{result.results.map((r) => r.command).join(" · ")}</span> · {result.duration_ms} ms
            {shown?.truncated ? " · showing the first 1,000 rows" : ""}
          </p>
          {shown && <ResultGrid columns={shown.columns} rows={shown.rows} />}
        </div>
      )}
    </div>
  );
}

export function ResultGrid({ columns, rows }: { columns: string[]; rows: (string | null)[][] }) {
  if (rows.length === 0) {
    return <p className="body-sm text-ink-muted">No rows.</p>;
  }
  return (
    <div className="max-h-[60vh] overflow-auto rounded-md border border-border bg-surface-raised">
      <table className="w-full border-collapse text-left">
        <thead className="sticky top-0 bg-surface-sunken">
          <tr>
            {columns.map((c, i) => (
              <th key={i} className="label whitespace-nowrap border-b border-border px-3 py-2 text-ink-muted">
                {c}
              </th>
            ))}
          </tr>
        </thead>
        <tbody>
          {rows.map((row, i) => (
            <tr key={i} className="border-b border-border last:border-0">
              {row.map((v, j) => (
                <td key={j} className="code max-w-[320px] truncate px-3 py-2 text-ink" title={v ?? "NULL"}>
                  {v === null ? <span className="text-ink-muted">NULL</span> : v}
                </td>
              ))}
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}
